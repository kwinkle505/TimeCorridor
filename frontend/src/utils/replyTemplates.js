// ==================== 2. 语气分析引擎 ====================
function analyzeTone(content) {
  if (!content) return { style: 'casual', emoji: false, useSlang: false, length: 'short', energy: 'normal' }

  const len = content.length
  const exclaimCount = (content.match(/[!！]/g) || []).length
  const questionCount = (content.match(/[?？]/g) || []).length
  const ellipsisCount = (content.match(/[….]{2,}/g) || []).length
  const newlineCount = (content.match(/\n/g) || []).length

  // 检测颜文字/emoji
  const emojiPatterns = /[\u{1F600}-\u{1F64F}]|[\u{1F300}-\u{1F5FF}]|[\u{1F680}-\u{1F6FF}]|[\u{2600}-\u{26FF}]|[\u{2700}-\u{27BF}]|[\u{1F900}-\u{1F9FF}]|[\u{1F1E0}-\u{1F1FF}]/u
  var kaomojiList = ['ಠ∀ಠ', 'ಥ_ಥ', '｡◕‿◕｡', '╯°□°）╯', '¯\\_(ツ)_/¯', '｡•́︿•̀｡', '´；ω；｀', '✿◠‿◠']
  var hasKaomoji = false
  for (var ki = 0; ki < kaomojiList.length; ki++) {
    if (content.indexOf(kaomojiList[ki]) !== -1) { hasKaomoji = true; break }
  }
  const hasEmoji = emojiPatterns.test(content) || hasKaomoji

  // 检测网络用语/梗
  const slangWords = ['哈哈', '笑死', '救命', '绝了', '离谱', '蚌埠住', '摆烂', '躺平', '内卷', '社死',
    '破防', '栓Q', 'yyds', '绝绝子', 'emo', 'crush', '特种兵', '显眼包', '挖呀挖',
    '尊嘟假嘟', '泰裤辣', 'Citywalk', '多巴胺', '精神状态', '遥遥领先',
    '科目三', '挖挖机', '汗流浃背', '家人们', '谁懂啊', '真香', '奥力给',
    ' duck不必', '芭比Q', '大冤种', '钝感力', '松弛感', '挖野菜']
  const slangCount = slangWords.reduce((sum, word) => sum + (content.includes(word) ? 1 : 0), 0)
  const useSlang = slangCount >= 1

  // 检测低落词
  const lowWords = ['呜呜', '难过', '崩溃', '想死', '好累', '绝望', '无助', '痛苦', '丧']
  const lowCount = lowWords.reduce((sum, word) => sum + (content.includes(word) ? 1 : 0), 0)

  // 检测轻松词
  const happyWords = ['开心', '快乐', '棒', '耶', '嘻嘻', '嘿嘿', 'nice', '好耶']
  const happyCount = happyWords.reduce((sum, word) => sum + (content.includes(word) ? 1 : 0), 0)

  // 判断风格
  let style = 'casual'
  if (len > 300 && newlineCount > 3) style = 'literary'
  else if (useSlang && exclaimCount > 2) style = 'energetic'
  else if (lowCount >= 2 || ellipsisCount > 3) style = 'melancholy'
  else if (len < 30 && questionCount <= 1) style = 'minimal'
  else if (hasEmoji) style = 'kawaii'
  else if (useSlang) style = 'meme'

  return {
    style,
    emoji: hasEmoji,
    useSlang,
    length: len < 50 ? 'short' : len < 150 ? 'medium' : 'long',
    energy: happyCount > lowCount ? 'high' : lowCount > happyCount ? 'low' : 'normal',
    exclaimCount,
    questionCount
  }
}

