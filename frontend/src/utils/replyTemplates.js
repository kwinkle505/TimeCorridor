// ==================== 7. 辅助函数 ====================
function pickRandom(arr) {
  return arr[Math.floor(Math.random() * arr.length)]
}

function pickRandomN(arr, n) {
  var shuffled = arr.slice().sort(function() { return Math.random() - 0.5 })
  return shuffled.slice(0, n)
}

function getMoodKey(moods) {
  if (!moods || !Array.isArray(moods)) return null
  var priority = ['焦虑', '迷茫', '思念', '遗憾', '感恩', '期待', '幸福', '勇敢']
  for (var i = 0; i < priority.length; i++) {
    if (moods.indexOf(priority[i]) !== -1) return priority[i]
  }
  return moods[0] || null
}

function getMatchedKeywords(content) {
  if (!content) return []
  var matched = []
  var keys = Object.keys(keywordMap)
  for (var i = 0; i < keys.length; i++) {
    if (content.indexOf(keys[i]) !== -1) matched.push(keys[i])
  }
  return matched
}

// ==================== 8. 主生成函数 ====================
export function generateReply(content, recipient, moods, types) {
  // 语气分析
  var tone = analyzeTone(content)

  // 收信人
  var recipientName = (recipient || '自己').replace('十年后的', '') || '自己'
  var salutation = pickRandom(salutationMap[recipientName] || salutationMap['自己'])
  var signer = pickRandom(signMap[recipientName] || signMap['自己'])

  // 选择风格：根据语气分析结果
  var style = tone.style
  if (style === 'literary' || style === 'minimal') style = 'melancholy'
  else if (style === 'kawaii') style = 'casual'

  // 情绪数据
  var moodKey = getMoodKey(moods)
  var moodData = moodTones[moodKey] || moodTones['期待']
  var moodStyle = moodData[style] || moodData['casual']

  // 类型数据
  var typeKey = types || 'comfort'
  var typeData = typeStyles[typeKey] || typeStyles['comfort']
  var typeLines = typeData[style] || typeData['casual']

  // 关键词
  var matchedKeywords = getMatchedKeywords(content)

  // 生活细节
  var lifeDetail = pickRandom(lifeDetails[style] || lifeDetails['casual'])

  // === 组装回复 ===
  var parts = [salutation, '']

  // 开头
  parts.push(pickRandom(moodStyle.openers))

  // 如果是简短信件，回信也简短
  if (tone.length === 'short') {
    parts.push(pickRandom(moodStyle.closers))
    parts.push('')
    parts.push('—— ' + signer + '，于2036年7月10日')
    return parts.join('\n')
  }

  // 中间过渡
  parts.push(pickRandom(moodStyle.middles))

  // 关键词回应（最多2个）
  if (matchedKeywords.length > 0) {
    var selected = matchedKeywords.slice(0, 2)
    parts.push('')
    for (var k = 0; k < selected.length; k++) {
      parts.push(pickRandom(keywordMap[selected[k]]))
    }
  }

  // 生活细节
  parts.push('')
  parts.push(lifeDetail)

  // 类型特色句（2句）
  var selectedTypeLines = pickRandomN(typeLines, 2)
  parts.push('')
  parts.push(selectedTypeLines[0])
  parts.push(selectedTypeLines[1])

  // 结尾
  parts.push('')
  parts.push(pickRandom(moodStyle.closers))

  // 落款
  parts.push('')
  parts.push('—— ' + signer + '，于2036年7月10日')

  return parts.join('\n')
}

