/**
 * 获取情绪回复
 * @param {string} emotion - 情绪名称（开心/难过/生气/害怕/平静/迷茫）
 * @returns {string} 随机返回一条对应情绪的回复
 */
export function getReply(emotion) {
  const list = emotions[emotion]
  if (!list || list.length === 0) {
    return '谢谢你愿意和我分享。无论此刻是什么感受，你都不是一个人。'
  }
  const index = Math.floor(Math.random() * list.length)
  return list[index]
}

/**
 * 获取歌曲推荐
 * @param {string} emotion - 情绪名称（开心/难过/生气/害怕/平静/迷茫）
 * @returns {Object} 随机返回一首对应情绪的歌曲
 */
export function getSong(emotion) {
  const list = songs[emotion]
  if (!list || list.length === 0) {
    return { name: '暂无推荐', artist: '', reason: '任何音乐，只要是你喜欢的，就是最好的陪伴。' }
  }
  const index = Math.floor(Math.random() * list.length)
  return list[index]
}

/**
 * 获取所有支持的情绪列表
 * @returns {string[]}
 */
export function getEmotionList() {
  return Object.keys(emotions)
}

